// Generates src/gui/PhsFontAtlas.hpp: anti-aliased glyph bitmaps of the Inter typeface
// (SIL Open Font License 1.1, https://rsms.me/inter) at exactly the sizes and weights the
// editor uses, for the software renderer on Windows and Linux (no font engine at runtime).
//
// Build & run (macOS):
//   clang++ -std=c++17 -ObjC++ tools/gen_font_atlas.mm -framework CoreText -framework CoreGraphics \
//       -framework Foundation -o build/gen_font_atlas
//   build/gen_font_atlas <Inter-Regular.ttf> <Inter-Medium.ttf> <Inter-SemiBold.ttf> > src/gui/PhsFontAtlas.hpp
#import <Foundation/Foundation.h>
#import <CoreText/CoreText.h>
#import <CoreGraphics/CoreGraphics.h>
#include <cstdio>
#include <cmath>
#include <string>
#include <vector>

struct StyleSpec { float size; int weight; }; // weight: 0 regular, 1 medium, 2 semibold

// Every (size, weight) the editor draws text with
static const StyleSpec kStyles[] = {
    {7.5f, 2}, {8.0f, 2}, {8.5f, 1}, {8.5f, 2}, {9.0f, 0}, {9.0f, 2}, {10.0f, 1}, {10.0f, 2},
    {10.5f, 0}, {10.5f, 1}, {10.5f, 2}, {11.0f, 1}, {11.0f, 2}, {11.5f, 0}, {11.5f, 1}, {11.5f, 2},
    {12.0f, 0}, {15.0f, 2}, {17.0f, 2},
};

static std::vector<uint32_t> codepoints() {
    std::vector<uint32_t> cps;
    for (uint32_t c = 32; c < 127; ++c) cps.push_back(c);
    for (uint32_t c : {0x00B7u, 0x00E9u, 0x2014u, 0x2022u, 0x2026u, 0x2192u}) cps.push_back(c);
    return cps;
}

int main(int argc, char** argv) {
    @autoreleasepool {
        if (argc < 4) { std::fprintf(stderr, "usage: gen_font_atlas regular.ttf medium.ttf semibold.ttf\n"); return 1; }
        CGFontRef fonts[3];
        for (int w = 0; w < 3; ++w) {
            CGDataProviderRef dp = CGDataProviderCreateWithFilename(argv[1 + w]);
            fonts[w] = CGFontCreateWithDataProvider(dp);
            CGDataProviderRelease(dp);
            if (!fonts[w]) { std::fprintf(stderr, "cannot load %s\n", argv[1 + w]); return 1; }
        }
        const std::vector<uint32_t> cps = codepoints();

        std::printf("// GENERATED by tools/gen_font_atlas.mm - do not edit.\n");
        std::printf("// Glyph coverage bitmaps of Inter (Regular / Medium / SemiBold),\n");
        std::printf("// Copyright (c) 2016 The Inter Project Authors, SIL Open Font License 1.1\n");
        std::printf("// (https://openfontlicense.org). Used by the software renderer on Windows and Linux.\n");
        std::printf("#pragma once\n#include <cstdint>\n\nnamespace phs::fontatlas {\n\n");
        std::printf("struct Glyph { uint32_t cp; float advance; int16_t left, top; uint16_t w, h; uint32_t offset; };\n");
        std::printf("struct Face { float size; int weight; float ascent, descent; const Glyph* glyphs; int numGlyphs; const uint8_t* pixels; };\n\n");

        int si = 0;
        for (const auto& st : kStyles) {
            CTFontRef ct = CTFontCreateWithGraphicsFont(fonts[st.weight], st.size, nullptr, nullptr);
            const float ascent = CTFontGetAscent(ct), descent = CTFontGetDescent(ct);
            std::vector<uint8_t> pixels;
            std::string glyphLines;
            for (uint32_t cp : cps) {
                UniChar uc[2]; CGGlyph g[2] = {0, 0};
                int n = 1;
                if (cp > 0xFFFF) continue;
                uc[0] = static_cast<UniChar>(cp);
                if (!CTFontGetGlyphsForCharacters(ct, uc, g, n) || g[0] == 0) continue;
                CGSize adv;
                CTFontGetAdvancesForGlyphs(ct, kCTFontOrientationHorizontal, g, &adv, 1);
                const CGRect bb = CTFontGetBoundingRectsForGlyphs(ct, kCTFontOrientationHorizontal, g, nullptr, 1);
                int left = static_cast<int>(std::floor(bb.origin.x)) - 1;
                int bottom = static_cast<int>(std::floor(bb.origin.y)) - 1;
                int w = static_cast<int>(std::ceil(bb.origin.x + bb.size.width)) + 1 - left;
                int h = static_cast<int>(std::ceil(bb.origin.y + bb.size.height)) + 1 - bottom;
                if (cp == 32 || bb.size.width <= 0) { w = 0; h = 0; left = 0; bottom = 0; }
                const uint32_t offset = static_cast<uint32_t>(pixels.size());
                if (w > 0 && h > 0) {
                    std::vector<uint8_t> buf(static_cast<size_t>(w) * h, 0);
                    CGColorSpaceRef gray = CGColorSpaceCreateDeviceGray();
                    CGContextRef ctx = CGBitmapContextCreate(buf.data(), w, h, 8, w, gray, kCGImageAlphaNone);
                    CGColorSpaceRelease(gray);
                    CGContextSetGrayFillColor(ctx, 1.0, 1.0);
                    CGContextSetShouldAntialias(ctx, true);
                    CGContextSetShouldSmoothFonts(ctx, false);
                    CGPoint pos = CGPointMake(-left, -bottom);
                    CTFontDrawGlyphs(ct, g, &pos, 1, ctx);
                    CGContextRelease(ctx);
                    // CG bitmap rows run bottom-up in memory order top-first: row 0 is the top
                    pixels.insert(pixels.end(), buf.begin(), buf.end());
                }
                char line[160];
                std::snprintf(line, sizeof(line), "    {0x%X, %.4ff, %d, %d, %d, %d, %u},\n",
                              cp, adv.width, left, bottom + h, w, h, offset);
                glyphLines += line;
            }
            std::printf("inline constexpr Glyph kGlyphs%d[] = {\n%s};\n", si, glyphLines.c_str());
            std::printf("inline constexpr uint8_t kPixels%d[] = {", si);
            for (size_t i = 0; i < pixels.size(); ++i) std::printf("%s%u,", (i % 40 == 0) ? "\n    " : "", pixels[i]);
            if (pixels.empty()) std::printf("0");
            std::printf("\n};\n\n");
            CFRelease(ct);
            (void)ascent; (void)descent;
            ++si;
        }
        std::printf("inline constexpr Face kFaces[] = {\n");
        si = 0;
        for (const auto& st : kStyles) {
            CTFontRef ct = CTFontCreateWithGraphicsFont(fonts[st.weight], st.size, nullptr, nullptr);
            std::printf("    {%.2ff, %d, %.4ff, %.4ff, kGlyphs%d, static_cast<int>(sizeof(kGlyphs%d) / sizeof(Glyph)), kPixels%d},\n",
                        st.size, st.weight, CTFontGetAscent(ct), CTFontGetDescent(ct), si, si, si);
            CFRelease(ct);
            ++si;
        }
        std::printf("};\ninline constexpr int kNumFaces = %d;\n\n} // namespace phs::fontatlas\n", si);
        for (auto f : fonts) CGFontRelease(f);
    }
    return 0;
}
